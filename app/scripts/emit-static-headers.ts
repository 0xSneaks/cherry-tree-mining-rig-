/**
 * Write `_headers` into the static export.
 *
 * A static export ships HTML, not a server, so nothing in Next can set a
 * response header — and `frame-ancestors` is ignored in a <meta> tag, which
 * is exactly the directive Cherry web's iframe needs. What a static host can
 * do is read a `_headers` file and send those headers itself. Cloudflare
 * Pages and Netlify both do; GitHub Pages ignores the file, which costs
 * nothing, and is why Pages covers Cherry mobile but not Cherry web.
 *
 * The policy is imported rather than retyped so the static host sends exactly
 * what a Node deployment sends.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

import { securityHeaders } from '../src/lib/csp';

const OUT = resolve(import.meta.dirname, '..', 'out', '_headers');

const body = [
  '# Generated by scripts/emit-static-headers.ts — do not edit.',
  '# Read by Cloudflare Pages and Netlify. GitHub Pages ignores this file',
  '# and cannot send headers, so Cherry *web* needs one of the former.',
  '',
  '/*',
  ...securityHeaders({ dev: false }).map((h) => `  ${h.key}: ${h.value}`),
  '',
].join('\n');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`wrote ${OUT}`);
