/**
 * Write `_headers` into the static export.
 *
 * A static export ships HTML, not a server, so nothing in Next can set a
 * response header — and `frame-ancestors` is ignored in a `<meta>` tag, which
 * is exactly the directive Cherry web's iframe needs. What a static host can
 * do is read a `_headers` file and send those headers itself. Cloudflare
 * Pages and Netlify both do; GitHub Pages ignores the file, which costs
 * nothing, and is why Pages covers Cherry mobile but not Cherry web.
 *
 * No server also means no nonce, so `script-src` admits Next's inline
 * bootstrap and flight scripts by sha-256 digest, computed from the exported
 * HTML itself — one rule per document. The policy builder is imported rather
 * than retyped so the static host sends what a Node deployment sends, modulo
 * nonce-versus-hash.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

import { formatHeadersFile, staticHeaderRules } from '../src/lib/staticHostHeaders';

const APP_ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(APP_ROOT, 'out', '_headers');

/** Repo-name subpath the host serves under, e.g. `/cherry-tree-mining-rig-`. */
const BASE_PATH = process.env.NEXT_PUBLIC_BASE_PATH ?? '';

const body = [
  '# Generated by scripts/emit-static-headers.ts — do not edit.',
  '# Read by Cloudflare Pages and Netlify. GitHub Pages ignores this file',
  '# and cannot send headers, so Cherry *web* needs one of the former.',
  '#',
  '# script-src carries sha-256 digests of exactly the inline scripts the',
  '# export baked into each page — the nonce-less equivalent of the Node',
  "# deployment's per-request nonce. The /* fallback admits none: a page the",
  '# scanner missed fails closed instead of falling back to a blanket allow.',
  '',
  formatHeadersFile(staticHeaderRules(resolve(APP_ROOT, 'out'), BASE_PATH)),
].join('\n');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`wrote ${OUT}`);
