/**
 * Genesis-cap decision tables.
 *
 *   npx tsx scripts/model/genesis-cap.ts            # print markdown
 *   npx tsx scripts/model/genesis-cap.ts --write    # also write docs/models/
 *
 * Offline and deterministic: no RPC, no keys, no randomness. Every input is
 * an ASSUMPTION stated in the output. It does not choose a production cap.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import {
  ACTOR_WALLET_COUNTS,
  CANDIDATE_CAPS,
  ELIGIBLE_POPULATIONS,
  PARTICIPATION_LEVELS,
  maxCapForTarget,
  presetScenario,
  simulateCap,
  type Scenario,
} from '../../src/lib/model/genesisCap';

const pct = (b: number) => `${(b / 100).toFixed(2)}%`;
const n = (x: number) => Math.round(x).toLocaleString('en-US');

/** Genesis emission converted to seeds by replanting: SOL/day ÷ fee-inclusive price. */
function compoundSeeds(solPerDay: number, priceSol = 0.01, feeBps = 300): number {
  return Math.floor(solPerDay / (priceSol * (1 + feeBps / 10_000)));
}

export function buildReport(): { markdown: string; json: unknown } {
  const lines: string[] = [];
  const json: Record<string, unknown> = {};
  const push = (s = '') => lines.push(s);

  const base = presetScenario({ founderSeeds: 1_000 });
  push('# Genesis cap — scenario tables');
  push();
  push('Generated by `app/scripts/model/genesis-cap.ts` from `app/src/lib/model/genesisCap.ts`.');
  push('Deterministic (Pareto quantiles, no randomness). **Every input is an assumption, not measured data.**');
  push();
  push('Baseline assumptions: 10,000 eligible .skr wallets · 2% participate (200 wallets) · ordinary demand Pareto(min 5 seeds, α 1.16, max 100,000) ·');
  push('founder activation wants 1,000 seeds (capped like any wallet) · one actor wants 50,000 seeds across 5 wallets · no Genesis replanting unless stated · Public demand = 10,000 / 100,000 / 1,000,000 seeds after T0+24h (low / medium / high).');
  push();

  // 1. Cap sensitivity, baseline.
  push('## 1. Cap sensitivity (baseline: expected participation, 5-wallet actor)');
  push();
  push('| cap | Genesis seeds | cap binds for | deferred to Public | largest ordinary wallet | 5-wallet actor | founder | top-10 wallets | HHI | Genesis cohort after low / medium / high Public |');
  push('|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|');
  const sens = [...CANDIDATE_CAPS, null].map((c) => simulateCap(base, c));
  json.capSensitivity = sens;
  for (const r of sens) {
    push(
      `| ${r.cap === null ? 'none (reference)' : r.cap === 10 ? '10 (qualification test value only)' : n(r.cap)} | ${n(r.genesisFreshSeeds)} | ${pct(r.capBindingBps)} | ${n(r.deferredSeeds)} | ${pct(r.largestOrdinaryWalletBps)} | ${pct(r.actorBps)} | ${pct(r.founderBps)} | ${pct(r.top10WalletsBps)} | ${r.hhi} | ${r.afterPublic.map((p) => pct(p.genesisCohortBps)).join(' / ')} |`,
    );
  }
  push();

  // 2. Actor share by wallets controlled.
  push('## 2. Multi-wallet actor share of Genesis (baseline participation)');
  push();
  push(`| cap | ${ACTOR_WALLET_COUNTS.map((k) => `${k}-wallet actor`).join(' | ')} |`);
  push(`|---:|${ACTOR_WALLET_COUNTS.map(() => '---:').join('|')}|`);
  const actorMatrix: Record<string, Record<number, number>> = {};
  for (const c of CANDIDATE_CAPS) {
    const row = ACTOR_WALLET_COUNTS.map((k) => simulateCap({ ...base, actorWallets: k }, c).actorBps);
    actorMatrix[c] = Object.fromEntries(ACTOR_WALLET_COUNTS.map((k, i) => [k, row[i]!]));
    push(`| ${n(c)} | ${row.map(pct).join(' | ')} |`);
  }
  json.actorMatrix = actorMatrix;
  push();

  // 3. Participation × population.
  const focusCaps = [25, 50, 100, 250, 500, 1_000] as const;
  push('## 3. 5-wallet actor share across population × participation');
  push();
  push(`| eligible wallets | participation | participants | ${focusCaps.map((c) => `cap ${n(c)}`).join(' | ')} |`);
  push(`|---:|---|---:|${focusCaps.map(() => '---:').join('|')}|`);
  const grid: unknown[] = [];
  for (const pop of ELIGIBLE_POPULATIONS) {
    for (const lvl of PARTICIPATION_LEVELS) {
      const s: Scenario = { ...base, eligibleWallets: pop, participation: lvl.participation, name: lvl.name };
      const rs = focusCaps.map((c) => simulateCap(s, c));
      grid.push({ pop, level: lvl.name, participants: rs[0]!.participants, actorBps: rs.map((r) => r.actorBps) });
      push(`| ${n(pop)} | ${lvl.name} (${(lvl.participation * 100).toFixed(1)}%) | ${n(rs[0]!.participants)} | ${rs.map((r) => pct(r.actorBps)).join(' | ')} |`);
    }
  }
  json.populationGrid = grid;
  push();

  // 4. Undersubscription / oversubscription.
  push('## 4. Under- vs over-subscription at cap 100 and 500 (10,000 eligible)');
  push();
  push('| participation | cap | participants | Genesis seeds | cap binds for | deferred to Public | 5-wallet actor |');
  push('|---|---:|---:|---:|---:|---:|---:|');
  for (const lvl of PARTICIPATION_LEVELS) {
    for (const c of [100, 500]) {
      const r = simulateCap({ ...base, participation: lvl.participation }, c);
      push(`| ${lvl.name} | ${c} | ${n(r.participants)} | ${n(r.genesisFreshSeeds)} | ${pct(r.capBindingBps)} | ${n(r.deferredSeeds)} | ${pct(r.actorBps)} |`);
    }
  }
  push();

  // 5. Largest cap meeting a concentration target.
  push('## 5. Largest candidate cap keeping a k-wallet actor at or below a target share of Genesis');
  push();
  const targets = [500, 1_000, 2_000];
  push(`| eligible · participation | k | ${targets.map((t) => `≤ ${pct(t)}`).join(' | ')} |`);
  push(`|---|---:|${targets.map(() => '---:').join('|')}|`);
  const targetRows: unknown[] = [];
  for (const pop of [10_000, 50_000]) {
    for (const lvl of PARTICIPATION_LEVELS) {
      for (const k of [3, 5, 10]) {
        const s: Scenario = { ...base, eligibleWallets: pop, participation: lvl.participation, actorWallets: k };
        const caps = targets.map((t) => maxCapForTarget(s, CANDIDATE_CAPS, t));
        targetRows.push({ pop, level: lvl.name, k, caps });
        push(`| ${n(pop)} · ${lvl.name} | ${k} | ${caps.map((c) => (c === null ? 'none ≥ 10' : n(c))).join(' | ')} |`);
      }
    }
  }
  json.maxCapForTarget = targetRows;
  push();

  // 6. Genesis replanting.
  push('## 6. Genesis replanting (compounding is uncapped by design)');
  push();
  push('Genesis-day emission converted to seeds at 0.01 SOL + 3% fee. The actor and founder replant everything; half of ordinary wallets replant.');
  push();
  push('| Genesis-day emission | seeds from replanting | cap | actor before | actor after replanting |');
  push('|---:|---:|---:|---:|---:|');
  for (const solPerDay of [0.5, 5, 20]) {
    for (const c of [100, 500]) {
      const r = simulateCap({ ...base, genesisCompoundSeeds: compoundSeeds(solPerDay) }, c);
      push(`| ${solPerDay} SOL | ${n(compoundSeeds(solPerDay))} | ${c} | ${pct(r.actorBps)} | ${pct(r.actorBpsAfterCompounding)} |`);
    }
  }
  push();

  // 7. Public dilution.
  push('## 7. Public dilution of the Genesis cohort and of the actor');
  push();
  push('| cap | actor tops up in Public? | low Public: cohort / actor | medium Public: cohort / actor | high Public: cohort / actor |');
  push('|---:|---|---|---|---|');
  for (const c of [100, 500]) {
    for (const top of [false, true]) {
      const r = simulateCap({ ...base, actorTopsUpInPublic: top }, c);
      push(`| ${c} | ${top ? 'yes (to 50,000)' : 'no'} | ${r.afterPublic.map((p) => `${pct(p.genesisCohortBps)} / ${pct(p.actorBps)}`).join(' | ')} |`);
    }
  }
  push();
  push('Reading §7: the cap only shapes the first 24 hours. From T0+24h any wallet may buy without limit, so the');
  push('cap cannot bound long-run concentration — it bounds the head start. Public demand dilutes the Genesis cohort');
  push('(including any multi-wallet actor) in proportion to how much is planted after Genesis.');

  return { markdown: lines.join('\n') + '\n', json };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename);
if (isMain) {
  const { markdown, json } = buildReport();
  process.stdout.write(markdown);
  if (process.argv.includes('--write')) {
    const out = resolve(import.meta.dirname, '..', '..', '..', 'docs', 'models');
    mkdirSync(out, { recursive: true });
    writeFileSync(resolve(out, 'genesis-cap-scenarios.md'), markdown);
    writeFileSync(
      resolve(out, 'genesis-cap-scenarios.json'),
      JSON.stringify(json, (_, v) => (typeof v === 'bigint' ? v.toString() : v), 2) + '\n',
    );
  }
}
