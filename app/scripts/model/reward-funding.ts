/**
 * Production reward-funding decision tables.
 *
 *   npx tsx scripts/model/reward-funding.ts            # print markdown
 *   npx tsx scripts/model/reward-funding.ts --write    # also write docs/models/
 *
 * Offline and deterministic. Uses the exact on-chain funding rule. Only
 * external, non-purchase SOL is ever modelled as reward funding.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import {
  DAY,
  LAMPORTS_PER_SOL,
  fundingRow,
  previewFunding,
  requiredFundingLamports,
  simulateRefills,
  type FundingRow,
} from '../../src/lib/model/rewardFunding';

const PRICE = 10_000_000n; // 0.01 SOL — ASSUMPTION (current devnet config; production price undecided)
const FEE = 300n; // 3%
const SEED_LEVELS = [1_000n, 10_000n, 100_000n, 1_000_000n] as const; // 10 / 100 / 1,000 / 10,000 SOL planted

const sol = (l: bigint, d = 4) => {
  const whole = l / LAMPORTS_PER_SOL;
  const frac = (l % LAMPORTS_PER_SOL).toString().padStart(9, '0').slice(0, d);
  return d === 0 ? whole.toLocaleString('en-US') : `${whole.toLocaleString('en-US')}.${frac}`;
};
const apr = (bps: bigint) => `${(Number(bps) / 100).toLocaleString('en-US', { maximumFractionDigits: 2 })}%`;
const planted = (seeds: bigint) => `${seeds.toLocaleString('en-US')} seeds (${sol((seeds * PRICE * (10_000n + FEE)) / 10_000n, 1)} SOL)`;

export function buildReport(): { markdown: string; json: unknown } {
  const lines: string[] = [];
  const push = (s = '') => lines.push(s);
  const json: Record<string, unknown> = {};

  push('# Production reward funding — decision tables');
  push();
  push('Generated by `app/scripts/model/reward-funding.ts` from `app/src/lib/model/rewardFunding.ts` using the exact on-chain');
  push('`fund_rewards` rule. Seed price 0.01 SOL + 3% fee (ASSUMPTION: current devnet pricing; production pricing is undecided).');
  push('Planted levels are ASSUMPTIONS about participation. "Rate at that level" is what the accumulator would pay while that');
  push('many seeds are planted — it is not a return anyone will receive, and it falls as more seeds are planted.');
  push();

  // 1. Schedules.
  push('## 1. Schedule grid — emission and rate at planted level');
  push();
  push(`| funded | window | SOL / day | ${SEED_LEVELS.map((s) => `rate @ ${planted(s)}`).join(' | ')} |`);
  push(`|---:|---:|---:|${SEED_LEVELS.map(() => '---:').join('|')}|`);
  const grid: FundingRow[] = [];
  for (const amount of [25n, 50n, 100n, 250n, 500n]) {
    for (const days of [30n, 90n, 180n, 365n]) {
      const r = fundingRow({ amountSol: amount, durationDays: days, priceLamports: PRICE, feeBps: FEE, plantedSeeds: SEED_LEVELS });
      grid.push(r);
      push(`| ${amount} SOL | ${days} d | ${sol(r.emissionPerDayLamports)} | ${r.levels.map((l) => apr(l.aprBps)).join(' | ')} |`);
    }
  }
  json.scheduleGrid = grid;
  push();

  // 2. Required funding for phase floors.
  push('## 2. Funding required to hold a phase floor at a planted level');
  push();
  const bands = [
    ['Genesis floor 1,200%', 120_000n],
    ['Early Grove floor 600%', 60_000n],
    ['Growth floor 250%', 25_000n],
    ['60%', 6_000n],
  ] as const;
  push(`| target | ${SEED_LEVELS.map((s) => `${planted(s)} · 90 d`).join(' | ')} |`);
  push(`|---|${SEED_LEVELS.map(() => '---:').join('|')}|`);
  const req: unknown[] = [];
  for (const [label, bps] of bands) {
    const cells = SEED_LEVELS.map((s) => requiredFundingLamports(bps, s, PRICE, FEE, 90n));
    req.push({ label, bps, lamports: cells });
    push(`| ${label} | ${cells.map((c) => `${sol(c, 1)} SOL`).join(' | ')} |`);
  }
  json.requiredFunding = req;
  push();
  push('Every one of these must be paid in by the reward funder from external, non-purchase SOL. Purchase proceeds cannot');
  push('fund it (CAPITAL pays nothing; FEE never reaches REWARD). A high advertised rate at low participation is cheap;');
  push('holding it as participation grows is not — the rate falls hyperbolically with planted seeds.');
  push();

  // 3. Under/over participation for one candidate schedule.
  push('## 3. Under- and over-participation on a 100 SOL / 180-day schedule');
  push();
  push('| planted | rate at that level | emission per seed per day | whole schedule per seed (if planted level held) |');
  push('|---|---:|---:|---:|');
  const row = fundingRow({ amountSol: 100n, durationDays: 180n, priceLamports: PRICE, feeBps: FEE, plantedSeeds: [500n, ...SEED_LEVELS, 5_000_000n] });
  for (const l of row.levels) {
    push(`| ${planted(l.seeds)} | ${apr(l.aprBps)} | ${sol(l.perSeedPerDayLamports, 9)} SOL | ${sol(l.perSeedPerDayLamports * 180n, 6)} SOL |`);
  }
  push();

  // 4. Refill scenarios.
  push('## 4. Runway, Dormant transition and external refills');
  push();
  const sampleDays = [0n, 30n, 60n, 90n, 120n, 150n, 179n, 180n, 200n, 240n, 270n, 360n];
  const plans = [
    { name: 'A. 100 SOL / 180 d, no refill', plan: { initialSol: 100n, initialDays: 180n, refills: [], sampleDays } },
    {
      name: 'B. 100 SOL / 180 d + 25 SOL / 90 d at day 150 (before exhaustion)',
      plan: { initialSol: 100n, initialDays: 180n, refills: [{ atDay: 150n, sol: 25n, days: 90n }], sampleDays },
    },
    {
      name: 'C. 100 SOL / 180 d, Dormant, then 50 SOL / 90 d at day 200 (separately funded restart)',
      plan: { initialSol: 100n, initialDays: 180n, refills: [{ atDay: 200n, sol: 50n, days: 90n }], sampleDays },
    },
    {
      name: 'D. 100 SOL / 180 d + 5 SOL / 365 d at day 30 (small long top-up — LOWERS the rate)',
      plan: { initialSol: 100n, initialDays: 180n, refills: [{ atDay: 30n, sol: 5n, days: 365n }], sampleDays },
    },
  ];
  const refills: unknown[] = [];
  for (const p of plans) {
    const r = simulateRefills(p.plan);
    refills.push({ name: p.name, ...r });
    push(`**${p.name}** — total funded ${r.totalFundedSol} SOL; final Dormant start: day ${r.dormantFromDay ?? '— (not within horizon)'}`);
    push();
    push('| day | SOL / day | runway |');
    push('|---:|---:|---:|');
    for (const s of r.samples) push(`| ${s.day} | ${sol(s.rate * DAY)} | ${s.dormant ? 'Dormant (0)' : `${s.runwayDays} d`} |`);
    push();
  }
  json.refills = refills;

  // 5. Preview hazard.
  const cur = { rate: (100n * LAMPORTS_PER_SOL) / (180n * DAY), finish: 180n * DAY };
  const prev = previewFunding(cur, 30n * DAY, 5n * LAMPORTS_PER_SOL, 365n * DAY);
  json.previewHazard = prev;
  push('## 5. Refill preview hazard');
  push();
  push('`fund_rewards` re-spreads leftover + new amount over the NEW duration. In scenario D the 5 SOL top-up at day 30 with');
  push(`a 365-day duration changes the rate by ${(prev.rateChangeBps! / 100).toFixed(2)}% (lowersRate = ${prev.lowersRate}). Always run the`);
  push('preview (`app/scripts/ops/runway-report.ts --preview <sol> <days>`) and announce the resulting rate before funding.');
  push('Scenario B shows the same effect in a milder form: a 25 SOL / 90-day refill at day 150 extends runway but the per-day');
  push('rate drops from 0.5555 to 0.4629 SOL. Choose the duration from the rate you intend to announce, not the other way round.');

  return { markdown: lines.join('\n') + '\n', json };
}

const isMain = process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename);
if (isMain) {
  const { markdown, json } = buildReport();
  process.stdout.write(markdown);
  if (process.argv.includes('--write')) {
    const out = resolve(import.meta.dirname, '..', '..', '..', 'docs', 'models');
    mkdirSync(out, { recursive: true });
    writeFileSync(resolve(out, 'reward-funding-scenarios.md'), markdown);
    writeFileSync(
      resolve(out, 'reward-funding-scenarios.json'),
      JSON.stringify(json, (_, v) => (typeof v === 'bigint' ? v.toString() : v), 2) + '\n',
    );
  }
}
